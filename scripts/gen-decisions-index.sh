#!/bin/sh
# Generate decisions/INDEX.md from the per-file ADRs under decisions/.
#
# One file per decision lives at decisions/<domain>/<number>-<slug>.md with YAML
# frontmatter (see decisions/README.md). This script scans that tree and writes a
# single index grouped by domain and sorted by the decision's number (its issue
# number if present, else its PR number). The index is GENERATED — never hand-edit
# it. CI runs this script and fails if the committed INDEX.md is stale.
#
# Usage:
#   scripts/gen-decisions-index.sh            # rewrite decisions/INDEX.md in place
#   scripts/gen-decisions-index.sh --check    # exit non-zero if INDEX.md is stale
#
# Host-safe: POSIX sh + awk + sort only, no LLVM, no network.
set -eu

# Resolve repo root from this script's location so it works from any CWD.
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
root=$(CDPATH= cd -- "$script_dir/.." && pwd)
dec_dir="$root/decisions"
index="$dec_dir/INDEX.md"

# Fixed domain order; any other subdir is appended afterwards (sorted) so a new
# domain is still listed even before this list is updated.
ordered_domains="lang stdlib runtime tooling"

# Extract one frontmatter field ($2) from file ($1). Only the first YAML block
# (between the first two `---` lines) is consulted; the first match wins.
field() {
  awk -v key="$2" '
    NR==1 && $0=="---" { infm=1; next }
    infm && $0=="---"  { exit }
    infm {
      # split on the first ": "
      idx=index($0, ":")
      if (idx>0) {
        k=substr($0,1,idx-1)
        v=substr($0,idx+1)
        gsub(/^[ \t]+|[ \t]+$/,"",k)
        gsub(/^[ \t]+|[ \t]+$/,"",v)
        if (k==key) { print v; exit }
      }
    }
  ' "$1"
}

# Collect rows as: domain<TAB>key<TAB>status<TAB>date<TAB>title<TAB>relpath
rows=$(
  # Only decisions/<domain>/*.md — README/TEMPLATE/INDEX live at the top level and
  # are therefore never matched.
  find "$dec_dir" -mindepth 2 -maxdepth 2 -name '*.md' -type f 2>/dev/null | sort | while IFS= read -r f; do
    domain=$(basename "$(dirname "$f")")
    title=$(field "$f" title)
    status=$(field "$f" status)
    date=$(field "$f" date)
    issue=$(field "$f" issue)
    pr=$(field "$f" pr)
    key="$issue"
    [ -z "$key" ] && key="$pr"
    [ -z "$key" ] && key="0"
    rel=${f#"$dec_dir"/}
    [ -z "$title" ] && title="(missing title: $rel)"
    [ -z "$status" ] && status="?"
    printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$domain" "$key" "$status" "$date" "$title" "$rel"
  done
)

# Build the index into a temp file, then move into place (atomic).
tmp=$(mktemp "${TMPDIR:-/tmp}/zap-decidx.XXXXXX")
trap 'rm -f "$tmp"' EXIT INT TERM

{
  echo "# Decision index"
  echo
  echo "_Generated by \`scripts/gen-decisions-index.sh\` — do not edit by hand._"
  echo
  echo "Historical decisions \`D-0001…D-0243\` live in the frozen"
  echo "[\`DECISIONS.md\`](../DECISIONS.md); new decisions are the per-file ADRs"
  echo "listed here (see [\`README.md\`](README.md))."
  echo

  # Distinct domains actually present, in the fixed order first then any extras.
  present=$(printf '%s\n' "$rows" | awk -F'\t' 'NF{print $1}' | sort -u)
  emit_domain() {
    d="$1"
    block=$(printf '%s\n' "$rows" | awk -F'\t' -v d="$d" '$1==d')
    [ -z "$block" ] && return 0
    echo "## $d"
    echo
    echo "| # | Title | Status | Date |"
    echo "|---|-------|--------|------|"
    # Sort by numeric key ascending.
    printf '%s\n' "$block" | sort -t"$(printf '\t')" -k2,2n | while IFS="$(printf '\t')" read -r dom key status date title rel; do
      printf '| [%s](%s) | %s | %s | %s |\n' "$key" "$rel" "$title" "$status" "$date"
    done
    echo
  }

  seen=""
  for d in $ordered_domains; do
    if printf '%s\n' "$present" | grep -qx "$d"; then
      emit_domain "$d"
      seen="$seen $d"
    fi
  done
  # Any domain not in the fixed list (sorted), so nothing is silently dropped.
  printf '%s\n' "$present" | while IFS= read -r d; do
    [ -z "$d" ] && continue
    case " $seen " in *" $d "*) : ;; *) emit_domain "$d" ;; esac
  done
} > "$tmp"

if [ "${1:-}" = "--check" ]; then
  if [ -f "$index" ] && cmp -s "$tmp" "$index"; then
    echo "decisions/INDEX.md is up to date."
    exit 0
  fi
  echo "ERROR: decisions/INDEX.md is stale. Run scripts/gen-decisions-index.sh and commit the result." >&2
  if [ -f "$index" ]; then
    echo "--- diff (committed vs generated) ---" >&2
    diff -u "$index" "$tmp" >&2 || true
  fi
  exit 1
fi

mv "$tmp" "$index"
trap - EXIT INT TERM
echo "Wrote $index"
