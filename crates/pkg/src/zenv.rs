//! The `zenv` project environment (D-0052).
//!
//! `zenv` is a project-local, env-var-activated environment (venv-simple):
//! `source zenv/activate` sets variables and defines `deactivate`. When active
//! it points **both** ecosystems at project-local caches:
//!
//! - Zap deps resolve against `$ZAP_ZENV/pkg` (materialized from `zap.lock`),
//!   not the global cache — see [`module_search_paths`].
//! - `$ZAP_ZENV/venv` is a standard Python venv; activation sets `VIRTUAL_ENV`,
//!   `ZAP_PYENV`, `PYTHONPATH` (the venv's site-packages) and `PATH` so the
//!   embedded CPython (#27) and shell `python`/`pip` use it.
//!
//! The embedded interpreter starts via `Py_InitializeEx` (zaprt.c, owned by the
//! runtime work #80) and does not honor `VIRTUAL_ENV`/`ZAP_PYENV` on its own;
//! setting `PYTHONPATH` makes the venv functional today with no runtime change.
//! Teaching the interpreter to honor `ZAP_PYENV` directly is a runtime
//! follow-up (see design/0009-packaging.md).

use std::path::{Path, PathBuf};

/// The environment variable that marks an active zenv and locates it.
pub const ZAP_ZENV: &str = "ZAP_ZENV";
/// The environment variable overriding the global module cache location.
pub const ZAP_CACHE: &str = "ZAP_CACHE";
/// The directory name for the project environment.
pub const ZENV_DIR: &str = "zenv";
/// The module-cache subdirectory inside a zenv.
pub const PKG_SUBDIR: &str = "pkg";
/// The Python venv subdirectory inside a zenv.
pub const VENV_SUBDIR: &str = "venv";

/// The Zap module search path, given the relevant environment variables.
///
/// Pure so it can be unit-tested without mutating process env (the integration
/// test exercises the real flip via a subprocess). When a zenv is active the
/// search path is `$ZAP_ZENV/pkg`; otherwise it is the global cache
/// (`$ZAP_CACHE`, else `<home>/.zap/pkg`, else `./.zap/pkg`).
pub fn module_search_paths(
    zap_zenv: Option<&str>,
    zap_cache: Option<&str>,
    home: Option<&str>,
) -> Vec<PathBuf> {
    if let Some(z) = zap_zenv.filter(|s| !s.is_empty()) {
        return vec![join_slash(z, &[PKG_SUBDIR])];
    }
    if let Some(c) = zap_cache.filter(|s| !s.is_empty()) {
        return vec![PathBuf::from(c)];
    }
    let base = home.filter(|s| !s.is_empty()).unwrap_or(".");
    vec![join_slash(base, &[".zap", PKG_SUBDIR])]
}

/// Join path components with a forward slash, the one separator Zap uses on every
/// platform (Python-faithful: Python uses `/` and Windows accepts it in every API;
/// `std::path::Path::join` would insert a backslash on Windows, which is both
/// non-portable in Zap module paths and user-visible in `zap zenv path`). On POSIX
/// this is byte-identical to the previous `Path::join`. A component that is already
/// absolute (or the base already ending in a separator) is not double-separated.
fn join_slash(base: &str, subs: &[&str]) -> PathBuf {
    let mut s = base.to_string();
    for sub in subs {
        if !s.is_empty() && !s.ends_with('/') && !s.ends_with('\\') {
            s.push('/');
        }
        s.push_str(sub);
    }
    PathBuf::from(s)
}

/// Read the real process environment and return the active module search path.
pub fn module_search_paths_from_env() -> Vec<PathBuf> {
    let zenv = std::env::var(ZAP_ZENV).ok();
    let cache = std::env::var(ZAP_CACHE).ok();
    let home = std::env::var("HOME").ok();
    module_search_paths(zenv.as_deref(), cache.as_deref(), home.as_deref())
}

/// The `zenv/activate` script for a zenv rooted at the absolute path `zenv_abs`.
///
/// `source`-ing it sets `ZAP_ZENV`, points the Python venv up (`VIRTUAL_ENV`,
/// `ZAP_PYENV`, `PYTHONPATH`, `PATH`), and defines a `deactivate` function that
/// restores the prior environment. Written for bash/zsh.
pub fn activate_script(zenv_abs: &Path) -> String {
    let dir = zenv_abs.display();
    format!(
        r#"# zenv activate — `source zenv/activate` (bash/zsh).
# Generated by `zap zenv create`; do not edit. See design/0009-packaging.md.

if [ -n "${{ZAP_ZENV:-}}" ]; then
    echo "zenv: an environment is already active ($ZAP_ZENV); run 'deactivate' first" >&2
    return 1 2>/dev/null || exit 1
fi

_ZENV_DIR="{dir}"

# Save prior state so `deactivate` can restore it exactly.
_ZENV_OLD_PATH="${{PATH:-}}"
_ZENV_OLD_VIRTUAL_ENV="${{VIRTUAL_ENV:-}}"
_ZENV_OLD_PYTHONPATH="${{PYTHONPATH:-}}"

# Zap module resolution -> the project-local cache.
export ZAP_ZENV="$_ZENV_DIR"

# Python venv -> the embedded CPython (#27) and the shell's python/pip.
export VIRTUAL_ENV="$_ZENV_DIR/{venv}"
export ZAP_PYENV="$_ZENV_DIR/{venv}"
export PATH="$_ZENV_DIR/{venv}/bin:$PATH"
for _sp in "$_ZENV_DIR"/{venv}/lib/python*/site-packages; do
    if [ -d "$_sp" ]; then
        export PYTHONPATH="$_sp${{PYTHONPATH:+:$PYTHONPATH}}"
    fi
done
unset _sp

deactivate() {{
    export PATH="$_ZENV_OLD_PATH"
    if [ -n "$_ZENV_OLD_VIRTUAL_ENV" ]; then
        export VIRTUAL_ENV="$_ZENV_OLD_VIRTUAL_ENV"
    else
        unset VIRTUAL_ENV
    fi
    if [ -n "$_ZENV_OLD_PYTHONPATH" ]; then
        export PYTHONPATH="$_ZENV_OLD_PYTHONPATH"
    else
        unset PYTHONPATH
    fi
    unset ZAP_ZENV ZAP_PYENV
    unset _ZENV_OLD_PATH _ZENV_OLD_VIRTUAL_ENV _ZENV_OLD_PYTHONPATH _ZENV_DIR
    unset -f deactivate
}}

echo "zenv: activated $_ZENV_DIR (run 'deactivate' to exit)"
"#,
        venv = VENV_SUBDIR,
    )
}

/// The `zenv/` directory under a project root.
pub fn zenv_dir(root: &Path) -> PathBuf {
    root.join(ZENV_DIR)
}

/// The Zap module cache directory inside a project's zenv.
pub fn pkg_dir(root: &Path) -> PathBuf {
    zenv_dir(root).join(PKG_SUBDIR)
}

/// The Python venv directory inside a project's zenv.
pub fn venv_dir(root: &Path) -> PathBuf {
    zenv_dir(root).join(VENV_SUBDIR)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn active_zenv_points_at_pkg_cache() {
        let paths = module_search_paths(Some("/proj/zenv"), None, Some("/home/u"));
        assert_eq!(paths, vec![PathBuf::from("/proj/zenv/pkg")]);
    }

    #[test]
    fn inactive_uses_cache_override_then_home() {
        assert_eq!(
            module_search_paths(None, Some("/custom/cache"), Some("/home/u")),
            vec![PathBuf::from("/custom/cache")]
        );
        assert_eq!(
            module_search_paths(None, None, Some("/home/u")),
            vec![PathBuf::from("/home/u/.zap/pkg")]
        );
    }

    #[test]
    fn empty_env_values_are_ignored() {
        // An exported-but-empty ZAP_ZENV must not count as active.
        assert_eq!(
            module_search_paths(Some(""), None, Some("/home/u")),
            vec![PathBuf::from("/home/u/.zap/pkg")]
        );
    }

    #[test]
    fn activate_script_sets_and_restores() {
        let s = activate_script(Path::new("/proj/zenv"));
        assert!(s.contains("export ZAP_ZENV=\"$_ZENV_DIR\""));
        assert!(s.contains("export VIRTUAL_ENV=\"$_ZENV_DIR/venv\""));
        assert!(s.contains("export ZAP_PYENV=\"$_ZENV_DIR/venv\""));
        assert!(s.contains("site-packages"));
        assert!(s.contains("deactivate()"));
        assert!(s.contains("unset ZAP_ZENV ZAP_PYENV"));
        assert!(s.contains("/proj/zenv"));
    }
}
