//! The tool-generated, committed lockfile, `zap.lock` (D-0052).
//!
//! The lockfile is the fully-resolved build list: every module MVS selected,
//! its exact version, its source, and an integrity `checksum`. A checkout with
//! a `zap.lock` rebuilds identically. It is generated — never hand-edited — so
//! plain serde round-tripping (no comment preservation) is fine.

use serde::{Deserialize, Serialize};

use crate::error::{Error, Result};

/// The lockfile format version (bumped on an incompatible schema change).
pub const FORMAT_VERSION: u32 = 1;

/// A parsed `zap.lock`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lockfile {
    pub version: u32,
    /// The build list, one `[[module]]` per selected module, sorted by name
    /// then version for a stable, reviewable diff.
    #[serde(default, rename = "module")]
    pub modules: Vec<LockedModule>,
}

/// One resolved module in the build list.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedModule {
    pub name: String,
    pub version: String,
    /// `git+<url>` or `path+<dir>` (see `manifest::Source::lock_string`).
    pub source: String,
    /// `zap1:<hex>` content checksum, when known (absent for not-yet-fetched
    /// git sources).
    #[serde(skip_serializing_if = "Option::is_none", default)]
    pub checksum: Option<String>,
}

impl Lockfile {
    /// A new, empty lockfile at the current format version.
    pub fn new(mut modules: Vec<LockedModule>) -> Lockfile {
        modules.sort_by(|a, b| a.name.cmp(&b.name).then(a.version.cmp(&b.version)));
        Lockfile {
            version: FORMAT_VERSION,
            modules,
        }
    }

    /// Parse lockfile text.
    pub fn parse(text: &str) -> Result<Lockfile> {
        toml::from_str(text).map_err(|e| Error::Lockfile(e.to_string()))
    }

    /// Serialize to lockfile text, with a leading "do not edit" banner.
    pub fn to_toml(&self) -> Result<String> {
        let body = toml::to_string_pretty(self).map_err(|e| Error::Lockfile(e.to_string()))?;
        Ok(format!(
            "# This file is generated by `zap`; do not edit it by hand.\n\
             # It is committed so builds are reproducible (D-0052).\n{body}"
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trip() {
        let lock = Lockfile::new(vec![
            LockedModule {
                name: "jsonlib".into(),
                version: "1.4.0".into(),
                source: "git+https://example.com/jsonlib.git".into(),
                checksum: Some("zap1:abcd".into()),
            },
            LockedModule {
                name: "mathx".into(),
                version: "0.2.0".into(),
                source: "path+../mathx".into(),
                checksum: None,
            },
        ]);
        let text = lock.to_toml().unwrap();
        assert!(text.contains("do not edit"));
        assert!(text.contains("[[module]]"));
        let back = Lockfile::parse(&text).unwrap();
        assert_eq!(lock, back);
        // A module with no checksum omits the key entirely.
        assert!(!text.contains("checksum = \"\""));
    }

    #[test]
    fn modules_are_sorted() {
        let lock = Lockfile::new(vec![
            LockedModule {
                name: "zed".into(),
                version: "1.0.0".into(),
                source: "path+z".into(),
                checksum: None,
            },
            LockedModule {
                name: "aaa".into(),
                version: "1.0.0".into(),
                source: "path+a".into(),
                checksum: None,
            },
        ]);
        assert_eq!(lock.modules[0].name, "aaa");
        assert_eq!(lock.modules[1].name, "zed");
    }
}
