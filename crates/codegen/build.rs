//! Build script for `zapc_codegen`.
//!
//! The crate embeds the C runtime sources into the compiler binary with
//! `include_str!` (see `src/lib.rs`: `RUNTIME_C`, `RUNTIME_GC_C`,
//! `RUNTIME_RACE_C`, and the Windows / netpoller translation units). Rust's own
//! `include_str!` dependency tracking is not reliably honoured across a CI
//! `target/` cache restore (restored artifacts can carry mtimes that make Cargo
//! treat the crate as fresh), so a change to a runtime `.c` / `.inc.c` / `.h`
//! file **alone** — without also touching a `.rs` file — could leave the old
//! runtime baked into the rebuilt compiler. That silently shipped a stale
//! runtime (e.g. the data-race detector's no-op slice-1 stubs instead of the
//! slice-2 engine, #678).
//!
//! Emitting an explicit `rerun-if-changed` for every embedded runtime file makes
//! Cargo rebuild this crate whenever any of them changes, so the embedded
//! runtime always matches the source tree.
//!
//! The SIMD sort accelerator (#933) vendors two header libraries (x86-simd-sort
//! and Highway) under `third_party/`. The standalone compiler can't reference the
//! source tree at a user's `zap build` time, so every vendored header is embedded
//! into the binary: this script generates `$OUT_DIR/vendored_sort.rs` with a
//! `&[(relpath, contents)]` table that `lib.rs` writes into the per-build runtime
//! dir (preserving structure) and points the C++ compiler's `-I` at.

use std::path::Path;

fn main() {
    // Master runtime TU + the standalone-object translation units (NOT the
    // `runtime/` fragments — those are globbed below). `src/lib.rs` pulls each in
    // with `include_str!` / `include_bytes!`; keep this list in sync with those
    // macros. The per-module/per-accel fragments live under `src/runtime/` and are
    // listed in `src/runtime_manifest.rs`; the glob below covers the whole subtree
    // so adding a fragment needs no edit here.
    const EMBEDDED_RUNTIME_FILES: &[&str] = &[
        "src/zaprt.c",
        "src/zap_ctx_win_x64.c",
        "src/zap_win_a3.c",
        "src/zap_np_iocp.c",
        "src/zap_np_iocp.h",
        // FFT backend (#929): the C++ wrapper and the vendored PocketFFT header
        // it includes, both embedded and written out at compile time.
        "src/zapfft.cpp",
        "../../third_party/pocketfft/pocketfft_hdronly.h",
        // SIMD sort accelerator (#933, epic #139): the two per-ISA C++ kernels
        // (their vendored headers are embedded below; the dispatch seam is a
        // `runtime/` fragment covered by the glob).
        "src/zapxsort.cpp",
        "src/zaphwysort.cpp",
    ];
    for f in EMBEDDED_RUNTIME_FILES {
        println!("cargo:rerun-if-changed={f}");
    }

    // Every runtime C fragment + header under `src/runtime/` (the per-module and
    // per-accel bodies that `zaprt.c` `#include`s). A fragment-only edit must
    // rebuild this crate so the embedded runtime never goes stale (#678); globbing
    // the subtree means a NEW fragment is tracked automatically, with no third
    // list to keep in sync beyond `runtime_manifest.rs`.
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    rerun_for_runtime_fragments(&Path::new(&manifest_dir).join("src/runtime"));

    // Embed every vendored SIMD-sort header (+ Highway's one needed `abort.cc`)
    // into the compiler, keyed by its path relative to `third_party/`.
    let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let third_party = Path::new(&manifest).join("../../third_party");
    let roots = ["x86-simd-sort/src", "x86-simd-sort/lib", "highway/hwy"];
    let mut entries: Vec<(String, String)> = Vec::new();
    for root in roots {
        let base = third_party.join(root);
        collect(&base, &third_party, &mut entries);
    }
    entries.sort();
    let out = std::env::var("OUT_DIR").unwrap();
    let mut gen = String::from(
        "// @generated by build.rs — embedded vendored SIMD-sort headers (#933).\n\
         pub static VENDORED_SORT_FILES: &[(&str, &str)] = &[\n",
    );
    for (rel, abs) in &entries {
        gen.push_str(&format!("    ({rel:?}, include_str!({abs:?})),\n"));
        println!("cargo:rerun-if-changed={abs}");
    }
    gen.push_str("];\n");
    std::fs::write(Path::new(&out).join("vendored_sort.rs"), gen).expect("write vendored_sort.rs");

    // Re-run if the build script itself changes.
    println!("cargo:rerun-if-changed=build.rs");
}

/// Collect `*.h` / `*.hpp` / `*.inc` (and the single `abort.cc` Highway's static
/// vqsort path links) under `dir`, as `(path-relative-to-third_party, abspath)`.
fn collect(dir: &Path, third_party: &Path, out: &mut Vec<(String, String)>) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            collect(&p, third_party, out);
            continue;
        }
        let keep = match p.extension().and_then(|x| x.to_str()) {
            Some("h") | Some("hpp") | Some("inc") => true,
            Some("cc") => p.file_name().and_then(|n| n.to_str()) == Some("abort.cc"),
            _ => false,
        };
        if !keep {
            continue;
        }
        let rel = p
            .strip_prefix(third_party)
            .unwrap()
            .to_string_lossy()
            .replace('\\', "/");
        let abs = p.to_string_lossy().to_string();
        out.push((rel, abs));
    }
}

/// Emit `cargo:rerun-if-changed` for every file under `dir` (the `src/runtime/`
/// fragment subtree), recursively. Rust's `include_str!` dependency tracking is
/// not reliably honoured across a CI `target/` cache restore, so a fragment-only
/// edit must be declared here or the rebuilt compiler can keep a stale runtime.
fn rerun_for_runtime_fragments(dir: &Path) {
    let Ok(rd) = std::fs::read_dir(dir) else {
        return;
    };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            rerun_for_runtime_fragments(&p);
        } else {
            println!("cargo:rerun-if-changed={}", p.to_string_lossy());
        }
    }
}
